function setup() {
  createCanvas(400, 400);
}

function draw() {
  // 背景颜色：温馨的浅黄色
  background(245, 235, 215);
  
  // 消除描边描边的粗糙感，设置平滑
  strokeWeight(3);
  stroke(40); // 深色描边
  
  // ==================== 1. 猫咪身体 ====================
  fill(120, 110, 100); // 狸花猫的灰色/棕灰色基调
  ellipse(200, 290, 180, 160); 
  
  // 肚皮（浅色）
  noStroke();
  fill(220, 210, 195);
  ellipse(200, 310, 110, 100);
  stroke(40);
  
  // ==================== 2. 猫耳朵 ====================
  // 左耳朵
  fill(120, 110, 100);
  triangle(120, 160, 140, 100, 175, 135);
  // 左耳内耳（粉色）
  fill(240, 170, 170);
  triangle(130, 150, 145, 110, 165, 135);
  
  // 右耳朵
  fill(120, 110, 100);
  triangle(280, 160, 260, 100, 225, 135);
  // 右耳内耳（粉色）
  fill(240, 170, 170);
  triangle(270, 150, 255, 110, 235, 135);
  
  // ==================== 3. 猫头 ====================
  fill(120, 110, 100);
  ellipse(200, 170, 160, 130); // 略扁的圆形显得可爱
  
  // ==================== 4. 狸花猫特色斑纹（深色） ====================
  fill(60, 55, 50); // 深色条纹颜色
  noStroke();
  
  // 额头“M”字斑纹
  triangle(200, 115, 195, 135, 205, 135); // 中间小尖
  triangle(190, 115, 185, 130, 195, 130); // 左小尖
  triangle(210, 115, 205, 130, 215, 130); // 右小尖
  rect(185, 113, 30, 4); // 连接线
  
  // 两侧脸颊的花纹
  triangle(122, 160, 145, 160, 145, 165); // 左脸颊纹1
  triangle(122, 175, 140, 172, 140, 177); // 左脸颊纹2
  triangle(278, 160, 255, 160, 255, 165); // 右脸颊纹1
  triangle(278, 175, 255, 172, 255, 177); // 右脸颊纹2
  
  // 身体上的条纹
  ellipse(120, 280, 30, 10);
  ellipse(125, 300, 25, 8);
  ellipse(280, 280, 30, 10);
  ellipse(275, 300, 25, 8);
  
  stroke(40); // 重新开启描边
  
  // ==================== 5. 眼睛（狸花猫经典的绿眼） ====================
  // 左眼珠
  fill(150, 210, 100); // 经典黄绿色
  ellipse(165, 165, 30, 30);
  // 右眼珠
  ellipse(235, 165, 30, 30);
  
  // 瞳孔（黑眼仁）与高光
  fill(30);
  ellipse(165, 165, 14, 24); // 略微收缩的猫瞳孔
  ellipse(235, 165, 14, 24);
  
  fill(255); // 眼睛高光
  noStroke();
  ellipse(161, 159, 6, 6);
  ellipse(231, 159, 6, 6);
  stroke(40);
  
  // ==================== 6. 鼻子与嘴巴 ====================
  // 粉色小鼻子
  fill(230, 130, 140);
  triangle(200, 183, 194, 177, 206, 177);
  
  // 嘴巴（人字嘴）
  noFill();
  arc(193, 183, 14, 12, 0, HALF_PI + QUARTER_PI);
  arc(207, 183, 14, 12, QUARTER_PI, PI);
  
  // 红润的小腮红
  noStroke();
  fill(255, 150, 150, 150);
  ellipse(140, 185, 15, 10);
  ellipse(260, 185, 15, 10);
  stroke(40);
  
  // ==================== 7. 猫胡须 ====================
  // 左边胡须
  line(135, 180, 95, 175);
  line(135, 185, 90, 187);
  line(135, 190, 98, 199);
  
  // 右边胡须
  line(265, 180, 305, 175);
  line(265, 185, 310, 187);
  line(265, 190, 302, 199);
}
